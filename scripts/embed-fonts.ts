import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

interface EmbeddedFont {
  /** @fontsource package name, e.g. noto-sans. */
  family: string;
  theme: string;
  regularExport: string;
  boldExport: string;
}

const FONTS: EmbeddedFont[] = [
  { family: "noto-sans", theme: "modern-europass", regularExport: "notoSansRegular", boldExport: "notoSansBold" },
  // Caladea is metric-compatible with Cambria, the font of the Clera template.
  { family: "caladea", theme: "clera", regularExport: "caladeaRegular", boldExport: "caladeaBold" },
];

for (const font of FONTS) {
  const packageDirectory = path.resolve(`node_modules/@fontsource/${font.family}`);
  const regular = await readFile(path.join(packageDirectory, `files/${font.family}-latin-400-normal.woff2`));
  const bold = await readFile(path.join(packageDirectory, `files/${font.family}-latin-700-normal.woff2`));
  const targetDirectory = path.resolve(`themes/${font.theme}/assets/fonts`);
  await mkdir(targetDirectory, { recursive: true });
  await copyFile(path.join(packageDirectory, "LICENSE"), path.join(targetDirectory, "OFL-1.1.txt"));
  await writeFile(
    path.resolve(`themes/${font.theme}/fonts.ts`),
    `// Generated by scripts/embed-fonts.ts from @fontsource/${font.family}.\nexport const ${font.regularExport} = ${JSON.stringify(regular.toString("base64"))};\nexport const ${font.boldExport} = ${JSON.stringify(bold.toString("base64"))};\n`,
    "utf8",
  );
  console.log(`Embedded ${font.family} regular and bold weights into themes/${font.theme}.`);
}
